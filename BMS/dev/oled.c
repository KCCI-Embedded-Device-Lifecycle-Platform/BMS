/* --- 초기화 커맨드 시퀀스 (데이터시트 권장 순서) --- */
static const uint8_t s_init_cmd[] = {
    0xAE,               /* Display OFF                       */
    0x20, 0x00,         /* Memory Addressing Mode = Horizontal*/
    0xB0,               /* Page start                        */
    0xC8,               /* COM scan direction 재매핑          */
    0x00, 0x10,         /* Column addr low/high              */
    0x40,               /* Start line = 0                    */
    0x81, 0x7F,         /* Contrast                          */
    0xA1,               /* Segment re-map                    */
    0xA6,               /* Normal display (A7 = 반전)         */
    0xA8, 0x3F,         /* Multiplex ratio = 64              */
    0xA4,               /* RAM 내용 출력                      */
    0xD3, 0x00,         /* Display offset = 0                */
    0xD5, 0x80,         /* Clock divide / osc freq           */
    0xD9, 0xF1,         /* Pre-charge period                 */
    0xDA, 0x12,         /* COM pins config (128x64 = 0x12)   */
    0xDB, 0x40,         /* VCOMH deselect level              */
    0x8D, 0x14,         /* Charge pump ON  (이거 빠지면 화면 안 켜짐) */
    0xAF                /* Display ON                        */
};

/* ------------------------------------------------------------------
 *  전송 계층 : 여기만 버스에 의존한다.
 * ------------------------------------------------------------------ */
static bool oled_tx(bool is_data, const uint8_t *p_data, uint16_t len)
{
    uint8_t tx[CFG_OLED_WIDTH + 1U];

    if (len > CFG_OLED_WIDTH) {
        return false;
    }
    tx[0] = is_data ? OLED_CTRL_DATA : OLED_CTRL_CMD;
    memcpy(&tx[1], p_data, len);
    return hw_i2c_write(CFG_OLED_I2C_ADDR, tx, (uint16_t)(len + 1U));
}

static bool oled_bus_setup(void)
{
    if (!hw_i2c_is_ready(CFG_OLED_I2C_ADDR)) {
        DBG_E("OLED no ACK at 0x%02X (try 0x3D)", CFG_OLED_I2C_ADDR);
        return false;
    }
    return true;
}

static bool oled_cmd(uint8_t c)
{
    return oled_tx(false, &c, 1U);
}

bool oled_init(void)
{
    uint16_t i;

    s_ok = false;

    if (!oled_bus_setup()) {
        return false;
    }

    for (i = 0; i < sizeof(s_init_cmd); i++) {
        if (!oled_cmd(s_init_cmd[i])) {
            DBG_E("OLED init cmd[%u] fail", i);
            return false;
        }
    }

    s_ok = true;
    oled_clear();
    oled_flush();
    DBG_I("OLED ok (SSD1306 128x64, I2C1 @0x%02X)", CFG_OLED_I2C_ADDR);
    return true;
}

void oled_clear(void)
{
    memset(s_fb, 0x00, sizeof(s_fb));
}

void oled_flush(void)
{
    uint8_t page;

    if (!s_ok) {
        return;
    }

    for (page = 0; page < OLED_PAGES; page++) {
        /* 페이지 시작 위치 지정 (컬럼 오프셋은 SH1106 대응) */
        (void)oled_cmd((uint8_t)(0xB0U + page));
        (void)oled_cmd((uint8_t)(0x00U | (CFG_OLED_COL_OFFSET & 0x0FU)));
        (void)oled_cmd((uint8_t)(0x10U | ((CFG_OLED_COL_OFFSET >> 4) & 0x0FU)));

        if (!oled_tx(true, &s_fb[page * CFG_OLED_WIDTH], CFG_OLED_WIDTH)) {
            s_ok = false;
            DBG_E("OLED flush fail (page %u)", page);
            return;
        }
    }
}

void oled_draw_char(uint8_t x, uint8_t page, char c)
{
    uint8_t i;
    uint8_t idx;

    if ((page >= OLED_PAGES) || (x + OLED_FONT_W > CFG_OLED_WIDTH)) {
        return;
    }
    if ((c < 0x20) || (c > 0x7E)) {
        c = ' ';
    }
    idx = (uint8_t)(c - 0x20);

    for (i = 0; i < 5U; i++) {
        s_fb[(page * CFG_OLED_WIDTH) + x + i] = s_font5x7[idx][i];
    }
    s_fb[(page * CFG_OLED_WIDTH) + x + 5U] = 0x00;      /* 자간 */
}

void oled_draw_str(uint8_t x, uint8_t page, const char *s)
{
    while ((*s != '\0') && ((x + OLED_FONT_W) <= CFG_OLED_WIDTH)) {
        oled_draw_char(x, page, *s++);
        x = (uint8_t)(x + OLED_FONT_W);
    }
}

void oled_printf(uint8_t x, uint8_t page, const char *fmt, ...)
{
    char    buf[24];
    va_list ap;

    va_start(ap, fmt);
    (void)vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    oled_draw_str(x, page, buf);
}

bool oled_is_ok(void)
{
    return s_ok;
}
